function setLanguage(next,{persist=true}={}){if(!['de','en'].includes(next))throw new Error('Unsupported language');lang=next;document.documentElement.lang=lang;document.title=tr('Pixelwerk – Dein Bild. Deine Möglichkeiten.');document.querySelector('meta[name="description"]')?.setAttribute('content',tr('Bilder direkt im Browser bearbeiten: Pinsel, Ebenen, Text, Zuschnitt und Effekte. Deine Bilder bleiben auf deinem Gerät.'));if(persist&&!root.pixelwerkDesktop){try{localStorage.setItem('pixelwerk-language',lang);}catch{}try{const url=new URL(location.href);url.searchParams.set('lang',lang);history.replaceState(history.state,'',url);}catch{}}return lang;}
function bindShell(root){
  // Only the original, static UI is bound. User names, text fields, and canvas pixels are excluded.
  const textNodes=[],attributes=[],walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){const node=walker.currentNode;if(node.nodeValue.trim())textNodes.push([node,node.nodeValue]);}
  root.querySelectorAll('[title],[aria-label],[placeholder]').forEach(el=>{for(const name of ['title','aria-label','placeholder'])if(el.hasAttribute(name))attributes.push([el,name,el.getAttribute(name)]);});
  return ()=>{textNodes.forEach(([node,value])=>node.nodeValue=fragment(value));attributes.forEach(([el,name,value])=>el.setAttribute(name,fragment(value)));};
}
root.PixelI18n={tr,html,htmlText:fragment,setLanguage,bindShell,get language(){return lang;}};
